# Короткие сообщения — почти всегда реплики в обсуждении, а не вакансия.
MIN_VACANCY_LENGTH = 200


def vacancy_marker_filter(vacancies: list[Vacancy]) -> list[Vacancy]:
    """Отсеивает сообщения, не похожие на вакансию.

    Применяется только к источникам с неструктурированным текстом (Telegram):
    у вакансий с сайтов и из API raw_text пустой, их пропускаем как есть."""
    result = []
    for v in vacancies:
        if not v.raw_text:
            result.append(v)
            continue
        if len(v.raw_text) < MIN_VACANCY_LENGTH:
            continue
        lowered = v.raw_text.lower()
        if any(marker in lowered for marker in ADVERT_MARKERS):
            continue
        if lowered.count("канал") > MAX_CHANNEL_MENTIONS:
            continue
        # Два и более признака события: одно слово может встретиться
        # и в настоящей вакансии («опыт проведения вебинаров»).
        if sum(1 for m in EVENT_MARKERS if m in lowered) >= 2:
            continue
        if any(marker in lowered for marker in VACANCY_MARKERS):
            result.append(v)
    return result


def geo_filter(vacancies: list[Vacancy]) -> list[Vacancy]:
    result = []
    for v in vacancies:
        if v.remote:
            result.append(v)
            continue
        city = (v.city or "").lower()
        if any(marker in city for marker in TARGET_CITY_MARKERS):
            result.append(v)
    return result


def stopword_filter(vacancies: list[Vacancy], stopwords: list[str] | None = None) -> list[Vacancy]:
    stopwords = _load_stopwords() if stopwords is None else stopwords
    result = []
    for v in vacancies:
        title = v.title.lower()
        hit_stopword = any(_stem_matches(stem, title) for stem in stopwords)
        if not hit_stopword or any(_stem_matches(stem, title) for stem in WHITELIST_STEMS):
            result.append(v)
    return result


def relevance_filter(vacancies: list[Vacancy]) -> list[Vacancy]:
    """Оставляет только вакансии по направлению «оценка и развитие персонала».

    Маркер ищется строго по названию, как и стоп-слова. По всему тексту поста
    искать нельзя: почти любая вакансия упоминает «обучение» и «мотивацию»
    в разделе условий, и тогда фильтр пропускает вообще всё.

    Слабый маркер засчитывается только вместе с HR-контекстом: иначе проходят
    «ассистент по развитию соцсетей» и «эксперт по обучению ИИ»."""
    result = []
    for v in vacancies:
        title = v.title.lower()
        # Профессия важнее предметной области: «менеджер по маркетингу
        # (HR Brand)» — это маркетинг, а не HR, сколько бы «HR» в нём ни было.
        title_stems = stems(v.title)
        if any(phrase_matches(role, title_stems) for role in NON_TARGET_ROLES):
            continue
        if any(_stem_matches(stem, title) for stem in STRONG_STEMS):
            result.append(v)
            continue
        foreign = any(_stem_matches(stem, title) for stem in FOREIGN_DOMAIN)
        if any(_stem_matches(stem, title) for stem in ROLE_COMBOS) and not foreign:
            result.append(v)
            continue
        weak_hit = any(_stem_matches(stem, title) for stem in WEAK_STEMS)
        context_hit = any(_stem_matches(stem, title) for stem in HR_CONTEXT)
        if weak_hit and context_hit:
            result.append(v)
    return result


def recruiting_filter(vacancies: list[Vacancy]) -> list[Vacancy]:
    """Отсеивает вакансии, где подбор персонала — основная работа.

    Проверяется по тексту поста, а не по названию: «HR-менеджер» бывает и
    руководителем HR-функции, и рекрутёром на потоке. Вакансия, где подбор
    только упоминается в контексте руководства процессом, остаётся."""
    result = []
    for v in vacancies:
        if not v.raw_text:
            result.append(v)
            continue
        text_stems = stems(f"{v.title} {v.raw_text}")
        if any(phrase_matches(m, text_stems) for m in STAFFING_MARKERS):
            continue
        duties = sum(1 for m in RECRUITING_DUTIES if phrase_matches(m, text_stems))
        oversight = sum(1 for m in RECRUITING_OVERSIGHT if phrase_matches(m, text_stems))
        if duties > MAX_RECRUITING_DUTIES and oversight < MIN_OVERSIGHT_TO_KEEP:
            continue
        result.append(v)
    return result


def resume_filter(vacancies: list[Vacancy]) -> list[Vacancy]:
    """Отсеивает резюме соискателей.

    Часть каналов публикует вакансии и резюме в одной ленте, а предфильтр
    по маркерам вакансии их не различает: «в поиске» и «резюме» есть и там,
    и там. Ищем по началу текста — резюме представляются в первых строках."""
    result = []
    for v in vacancies:
        head = f"{v.title}\n{v.raw_text[:400]}".lower()
        # Хештег автор ставит сам — признак надёжнее любых фраз.
        if any(tag in head for tag in RESUME_HASHTAGS):
            continue
        if not any(marker in head for marker in RESUME_MARKERS):
            result.append(v)
    return result


# Порядок шагов конвейера и человеческие названия причин отсева.
# Единственное место, где он задан: и apply_filters, и review.py берут его
# отсюда. Раньше список был продублирован, и review.py молча отстал на два
# фильтра, показывая неверную картину.
FILTER_STAGES = [
    ("не похоже на вакансию", vacancy_marker_filter),
    ("резюме соискателя", resume_filter),
    ("не по направлению", relevance_filter),
    ("подбор как основная работа", recruiting_filter),
    ("не тот регион", geo_filter),
    ("стоп-слово в названии", stopword_filter),
]


def apply_filters(vacancies: list[Vacancy]) -> list[Vacancy]:
    """Прогоняет вакансии по всем шагам в порядке FILTER_STAGES."""
    for _, stage in FILTER_STAGES:
        vacancies = stage(vacancies)
    return vacancies
