"""Признаки удалённой работы и целевого региона — общие для всех источников.

Раньше списки были продублированы в каждом адаптере и разъезжались.
Из-за этого «работа из дома» не считалась удалёнкой, и подработка,
которую владелец просил присылать, молча отсеивалась как «далеко от дома».
"""

REMOTE_MARKERS = [
    "удалён", "удален", "удалёнк", "удаленк", "remote", "дистанционн",
    # Частые формулировки в объявлениях о подработке.
    "из дома", "на дому", "из любой точки", "можно из любого города",
    "home office", "хоум-офис", "работа онлайн", "полностью онлайн",
]

# Гибрид: часть недели всё равно в офисе, значит удалённой работой это
# не является. 22 сентября в дайджест попал «HR-директор, Екатеринбург,
# гибрид 3/2»: в условиях стояло «два дня удалённо», и одного этого слова
# хватало, чтобы выставить флаг удалёнки и проскочить гео мимо проверки города.
#
# Решение владельца: гибрид в Нижнем Новгороде подходит, в любом другом
# городе нет. Поэтому гибрид не считается удалёнкой никогда, а нижегородский
# проходит гео обычным путём, по городу.
HYBRID_MARKERS = [
    "гибрид", "hybrid", "смешанный формат", "смешанный график",
    "день в офисе", "дня в офисе", "дней в офисе",
    "день в неделю в офисе", "дня в неделю в офисе", "дней в неделю в офисе",
    "частично удалён", "частично удален",
]

CITY_MARKERS = [
    "нижний новгород", "нижнем новгороде", "нижнего новгорода", "нижегородск",
]


def looks_hybrid(*texts: str) -> bool:
    haystack = " ".join(t for t in texts if t).lower()
    return any(marker in haystack for marker in HYBRID_MARKERS)


def looks_remote(*texts: str) -> bool:
    # Гибрид перевешивает упоминание удалёнки: «три дня в офисе, два удалённо»
    # это офисная вакансия с поблажкой, а не удалённая.
    if looks_hybrid(*texts):
        return False
    haystack = " ".join(t for t in texts if t).lower()
    return any(marker in haystack for marker in REMOTE_MARKERS)


def looks_target_city(*texts: str) -> bool:
    haystack = " ".join(t for t in texts if t).lower()
    return any(marker in haystack for marker in CITY_MARKERS)
